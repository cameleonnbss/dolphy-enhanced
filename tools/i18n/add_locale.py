#!/usr/bin/env python3
"""Writes `res/values-<tag>/strings.xml` for every language in core_translations.py.

Usage (from the repository root):
    python tools/i18n/add_locale.py            # write all locales
    python tools/i18n/add_locale.py fr de      # write only these

Only keys listed in `CORE_KEYS` are emitted, so each locale file stays small and
readable. Anything absent falls back to `res/values/strings.xml` (English) at
runtime, which is why partial translation is safe.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from core_translations import CORE_KEYS, TRANSLATIONS  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "app/src/main/res"


def escape(value: str) -> str:
    """Escape a plain string so Android's resource parser accepts it verbatim."""
    out = (
        value.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("'", "\\'")
        .replace('"', '\\"')
    )
    # A leading ? or @ would be parsed as a resource reference.
    if out.startswith(("?", "@")):
        out = "\\" + out
    return out


def write_locale(tag: str, strings: dict[str, str]) -> int:
    missing = [k for k in CORE_KEYS if k not in strings]
    keys = [k for k in CORE_KEYS if k in strings]

    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {tag}: core UI strings. Generated by tools/i18n/add_locale.py —",
        "     edit tools/i18n/core_translations.py, then re-run the script. -->",
        "<resources>",
    ]
    for key in keys:
        lines.append(f'    <string name="{key}">{escape(strings[key])}</string>')
    lines.append("</resources>")
    lines.append("")

    target = RES / f"values-{tag}" / "strings.xml"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines), encoding="utf-8")

    if missing:
        print(f"  {tag}: {len(keys)} keys, missing {len(missing)}: {', '.join(missing[:5])}…")
    return len(keys)


def main(argv: list[str]) -> int:
    wanted = argv or sorted(TRANSLATIONS)
    total = 0
    for tag in wanted:
        if tag not in TRANSLATIONS:
            print(f"no translations for '{tag}'", file=sys.stderr)
            return 1
        total += write_locale(tag, TRANSLATIONS[tag])
    print(f"{len(wanted)} locale(s) written, {total} strings total")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
